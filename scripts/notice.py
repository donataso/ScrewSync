#!/usr/bin/env python3
"""Regenerate the generated part of NOTICE.md (generate) or check its hash (check)."""
import argparse
import glob
import hashlib
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_webui  # noqa: E402

MARKER = "<!-- Generated by make notice. Do not edit below. -->"
HASH_RE = re.compile(r"^<!-- notice-hash: ([0-9a-f]{64}) -->$", re.M)

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_NOTICE_MD = os.path.join(_ROOT, "NOTICE.md")
_HASH_INPUTS = [os.path.join(_ROOT, "web", "firmware-client", "package-lock.json"), os.path.join(_ROOT, "west.yml")]
_WEB_META_DIR = os.path.join(_ROOT, ".build", "notice", "web")
_WEB_OUT_DIR = os.path.join(_ROOT, ".build", "notice", "web-out")
_NODE_MODULES_DIR = os.path.join(_ROOT, ".cache", "node_modules")
_CONTAINER_NODE_MODULES = "/work/firmware-client/node_modules"

# Tailwind's CSS ends up in the bundle without being a JS module.
_WEB_ALWAYS = ["tailwindcss"]

_LICENSE_FILE_RE = re.compile(r"^(licen[cs]e|copying)([-._].*)?$", re.I)
_NOTICE_FILE_RE = re.compile(r"^notice(\..*)?$", re.I)
_COPYRIGHT_LINE_RE = re.compile(r"^\s*(Copyright\s*(\(c\)|©|\d|\[)|\(c\)\s*\d)")
_YEAR_RE = re.compile(r"\b(?:19|20)\d\d\b")

warnings = []


def compute_hash():
    h = hashlib.sha256()
    for path in _HASH_INPUTS:
        with open(path, "rb") as f:
            h.update(f.read())
    return h.hexdigest()


def read_text(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read()


def find_files(directory, pattern):
    if not os.path.isdir(directory):
        return []
    return [os.path.join(directory, n) for n in sorted(os.listdir(directory))
            if pattern.match(n) and os.path.isfile(os.path.join(directory, n))]


def copyright_lines(text):
    return [l.strip() for l in text.splitlines() if _COPYRIGHT_LINE_RE.match(l)]


def strip_copyright(text):
    lines = [l.rstrip() for l in text.splitlines() if not _COPYRIGHT_LINE_RE.match(l)]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip("\n")


def parse_copyright(line):
    text = re.sub(r"(?i)spdx-filecopyrighttext:|copyright|\(c\)|©|all rights reserved\.?", " ", line)
    years = [int(y) for y in _YEAR_RE.findall(text)]
    holder = re.sub(r"\s+", " ", _YEAR_RE.sub(" ", text)).strip(" ,.-–:;")
    if holder in ("", "NONE", "NOASSERTION"):
        return None
    return holder, years


def add_holder(holders, line):
    parsed = parse_copyright(line)
    if not parsed:
        return
    holder, years = parsed
    lo, hi = holders.get(holder, (None, None))
    if years:
        lo = min(years + ([lo] if lo else []))
        hi = max(years + ([hi] if hi else []))
    holders[holder] = (lo, hi)


def format_holders(holders):
    out = []
    for holder in sorted(holders, key=str.lower):
        lo, hi = holders[holder]
        years = "" if not lo else str(lo) if lo == hi else "%d-%d" % (lo, hi)
        out.append(" ".join(p for p in ("Copyright (c)", years, holder) if p))
    return out


def license_ids(expression):
    """Distinct licenses of an SPDX expression; the first side of every OR."""
    ids = []
    for part in re.split(r"\s+AND\s+", expression.replace("(", " ").replace(")", " ")):
        alt = re.split(r"\s+OR\s+", part.strip())[0].split(" WITH ")[0].strip()
        if alt and alt not in ("NONE", "NOASSERTION") and alt not in ids:
            ids.append(alt)
    return ids


def file_license_ids(entries):
    """Licenses of one file; copyleft alternatives dropped when a permissive one is offered."""
    ids = [lic for e in entries for lic in license_ids(e)]
    permissive = [l for l in ids if not re.match(r"A?L?GPL", l)]
    return permissive or ids


def clean_url(url):
    if not url or url == "N/A":
        return ""
    url = re.sub(r"^git\+", "", url)
    url = re.sub(r"^git://", "https://", url)
    url = re.sub(r"^github:", "https://github.com/", url)
    if re.fullmatch(r"[\w.-]+/[\w.-]+", url):
        url = "https://github.com/" + url
    return re.sub(r"\.git$", "", url)


def read_tags(path):
    """(tag, value) pairs of an SPDX tag-value file; <text> blocks joined."""
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        if line.startswith("#") or ":" not in line:
            continue
        tag, value = line.split(":", 1)
        value = value.strip()
        if value.startswith("<text>"):
            while "</text>" not in value:
                value += "\n" + next(lines, "</text>")
            value = value[len("<text>"):value.index("</text>")]
        yield tag, value


def spdx_files(path):
    """(package, relative path, license ids, copyright text) of every file."""
    package = None
    current = None
    for tag, value in read_tags(path):
        if tag in ("PackageName", "FileName"):
            if current:
                yield current
                current = None
        if tag == "PackageName":
            package = value
        elif tag == "FileName":
            current = [package, value, [], ""]
        elif current and tag == "LicenseInfoInFile":
            current[2].append(value)
        elif current and tag == "FileCopyrightText":
            current[3] = value
    if current:
        yield current


def parse_west_list(path):
    projects = {}
    for line in read_text(path).splitlines():
        if line.count("|") == 2:
            name, project_path, url = line.split("|")
            projects[name] = (project_path, clean_url(url))
    return projects


def module_license_path(module_dir):
    yml = os.path.join(module_dir, "zephyr", "module.yml")
    m = re.search(r"license-path:\s*(\S+)", read_text(yml)) if os.path.isfile(yml) else None
    return os.path.join(module_dir, m.group(1)) if m else None


def zephyr_license_text(module_dir, zephyr_dir, license_id, sole):
    candidates = [os.path.join(module_dir, "LICENSES", license_id + ".txt")]
    if sole:
        candidates += find_files(module_dir, _LICENSE_FILE_RE)
    candidates.append(os.path.join(zephyr_dir, "LICENSES", license_id + ".txt"))
    for c in candidates:
        if os.path.isfile(c):
            return read_text(c)
    return None


def linked_libraries(spdx_dirs):
    """Prebuilt archives in the link maps: blob module dirs and SDK toolchain dirs."""
    blob_dirs, sdk_dirs = set(), set()
    for spdx_dir in spdx_dirs:
        map_file = os.path.join(os.path.dirname(os.path.normpath(spdx_dir)), "zephyr", "zephyr.map")
        for lib in set(re.findall(r"(/[^\s()]+\.a)\(", read_text(map_file))):
            if "/zephyr/blobs/" in lib:
                blob_dirs.add(lib.split("/zephyr/blobs/")[0])
            elif re.match(r".*?/gnu/[^/]+/", lib):
                sdk_dirs.add((re.match(r"(.*?/gnu/[^/]+)/", lib).group(1), os.path.basename(lib)))
    return blob_dirs, sdk_dirs


def sdk_components(sdk_libs):
    licenses = {}
    for toolchain_dir, lib in sorted(sdk_libs):
        base = os.path.join(toolchain_dir, "share", "licenses")
        if lib == "libc.a":
            files = [os.path.join(base, "picolibc", n) for n in ("COPYING.picolibc", "COPYING.NEWLIB")]
            licenses["picolibc"] = ("LicenseRef-picolibc", "https://github.com/picolibc/picolibc", files)
        elif lib in ("libgcc.a", "libstdc++.a", "libsupc++.a"):
            exception = os.path.join(base, "gcc", "COPYING.RUNTIME")
            if not (os.path.isfile(exception) and "RUNTIME LIBRARY EXCEPTION" in read_text(exception).upper()):
                warnings.append("%s: GCC runtime exception text not found, not excluded" % lib)
                licenses["gcc runtime"] = ("GPL-3.0-only", "https://gcc.gnu.org", [os.path.join(base, "gcc", "COPYING3")])
        else:
            warnings.append("unknown SDK library %s" % lib)
    components = []
    for name, (license_id, url, files) in sorted(licenses.items()):
        texts = [(license_id, read_text(f)) for f in files if os.path.isfile(f)]
        if len(texts) != len(files):
            warnings.append("license file missing for %s" % name)
        components.append(make_component(name, license_id, url, [], texts, False, ""))
    return components


def zephyr_components(spdx_dirs, west_list):
    projects = parse_west_list(west_list)
    projects.setdefault("zephyr", projects.get("manifest", ("", "")))
    zephyr_dir = projects["zephyr"][0]
    found = {}
    for spdx_dir in spdx_dirs:
        image = os.path.basename(os.path.dirname(os.path.normpath(spdx_dir)))
        for spdx in sorted(glob.glob(os.path.join(spdx_dir, "*.spdx"))):
            for package, rel_path, lics, copyright_text in spdx_files(spdx):
                if not package.endswith("-sources"):
                    continue
                name = package[:-len("-sources")]
                if name == "app":
                    if image != "mcuboot":
                        continue
                    name = "mcuboot"
                comp = found.setdefault(name, {"ids": [], "holders": {}})
                for lic in file_license_ids(lics):
                    if lic not in comp["ids"]:
                        comp["ids"].append(lic)
                for line in copyright_text.splitlines():
                    add_holder(comp["holders"], line)

    blob_dirs, sdk_dirs = linked_libraries(spdx_dirs)
    components = []
    for name in sorted(found):
        comp = found[name]
        if name not in projects:
            warnings.append("no west project for %s" % name)
            continue
        module_dir, url = projects[name]
        ids = sorted(comp["ids"])
        texts = []
        for lic in ids:
            text = zephyr_license_text(module_dir, zephyr_dir, lic, len(ids) == 1)
            if text is None:
                warnings.append("no license text for %s in %s" % (lic, name))
            else:
                texts.append((lic, text))
        holders = comp["holders"]
        if not holders:
            for path in find_files(module_dir, _LICENSE_FILE_RE):
                for line in copyright_lines(read_text(path)):
                    add_holder(holders, line)
        components.append(make_component(name, ", ".join(ids) or "NOASSERTION", url, format_holders(holders), texts,
                                         "Apache-2.0" in ids, module_dir))
    names_by_dir = {d: n for n, (d, _) in projects.items()}
    for module_dir in sorted(blob_dirs):
        name = names_by_dir.get(module_dir, os.path.basename(module_dir))
        blob_license = module_license_path(module_dir)
        text = read_text(blob_license) if blob_license and os.path.isfile(blob_license) else None
        if text is None:
            warnings.append("no blob license for %s" % name)
        blob_id = "Apache-2.0" if text and "Apache License" in text[:300] else "LicenseRef-blobs"
        components.append(make_component(name + " blobs", blob_id, projects.get(name, ("", ""))[1],
                                         [], [(blob_id, text)] if text else [], False, module_dir))
    components += sdk_components(sdk_dirs)
    return components


def make_component(name, license_expression, url, copyrights, texts, apache, notice_dir):
    notice = None
    if apache:
        files = find_files(notice_dir, _NOTICE_FILE_RE)
        notice = read_text(files[0]).strip("\n") if files else None
    return {"name": name, "license": license_expression, "url": url, "copyrights": copyrights, "texts": texts,
            "notice": notice}


def web_package_dirs(module_ids):
    dirs = {}
    for module_id in module_ids:
        module_id = module_id.lstrip("\0").split("?")[0]
        i = module_id.rfind("node_modules/")
        if i < 0 or not module_id.startswith(_CONTAINER_NODE_MODULES):
            continue
        parts = module_id[i + len("node_modules/"):].split("/")
        name = "/".join(parts[:2]) if parts[0].startswith("@") else parts[0]
        if not name.startswith("."):
            dirs[name] = module_id[:i] + "node_modules/" + name
    for name in _WEB_ALWAYS:
        dirs.setdefault(name, "%s/%s" % (_CONTAINER_NODE_MODULES, name))
    return {name: d.replace(_CONTAINER_NODE_MODULES, _NODE_MODULES_DIR, 1) for name, d in dirs.items()}


def npm_license_field(meta):
    value = meta.get("license") or meta.get("licenses")
    if isinstance(value, list):
        return " OR ".join(v.get("type", "") if isinstance(v, dict) else v for v in value)
    return value.get("type", "") if isinstance(value, dict) else value or ""


def web_components():
    modules_json = os.path.join(_WEB_META_DIR, "modules.json")
    os.makedirs(_WEB_META_DIR, exist_ok=True)
    if os.path.exists(modules_json):
        os.remove(modules_json)
    if not build_webui.run_in_container(
            _WEB_OUT_DIR, build_webui._NPM_INSTALL + " && npm run build",
            env=["NOTICE_MODULES=/work/notice/modules.json"], mounts=["%s:/work/notice" % _WEB_META_DIR]):
        sys.exit("notice: web build failed")
    with open(modules_json, encoding="utf-8") as f:
        dirs = web_package_dirs(json.load(f))

    components = []
    for name in sorted(dirs):
        pkg_dir = dirs[name]
        with open(os.path.join(pkg_dir, "package.json"), encoding="utf-8") as f:
            meta = json.load(f)
        repository = meta.get("repository")
        url = clean_url(repository.get("url", "") if isinstance(repository, dict) else repository or meta.get("homepage", ""))
        license_expression = npm_license_field(meta) or "NOASSERTION"
        texts = [(license_expression, read_text(p)) for p in find_files(pkg_dir, _LICENSE_FILE_RE)]
        if not texts:
            warnings.append("no license file in %s" % name)
        copyrights = []
        for _, text in texts:
            copyrights += [l for l in copyright_lines(text) if l not in copyrights]
        components.append(make_component(name, license_expression, url, copyrights, texts,
                                         "Apache-2.0" in license_expression, pkg_dir))
    return components


def fence(text):
    longest = max((len(m) for m in re.findall(r"`+", text)), default=0)
    ticks = "`" * max(3, longest + 1)
    return "%s\n%s\n%s" % (ticks, text, ticks)


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ")


def render_table(headers, rows):
    widths = [max(len(r[i]) for r in [headers] + rows) for i in range(len(headers))]
    line = lambda r: "| " + " | ".join(c.ljust(w) for c, w in zip(r, widths)) + " |"
    return "\n".join([line(headers), "| " + " | ".join("-" * w for w in widths) + " |"] + [line(r) for r in rows])


def render(components):
    components = sorted(components, key=lambda c: c["name"].lower())
    rows = [[cell(c["name"]), cell(c["license"]), cell(c["url"]), "<br>".join(cell(x) for x in c["copyrights"])]
            for c in components]

    groups = {}
    for c in components:
        for license_id, text in c["texts"]:
            body = strip_copyright(text)
            spdx_key = license_id if re.fullmatch(r"[A-Za-z0-9.+-]+", license_id) and not license_id.startswith("LicenseRef") else None
            group = groups.setdefault(spdx_key or " ".join(body.split()), {"body": body, "ids": [], "users": []})
            if license_id not in group["ids"]:
                group["ids"].append(license_id)
            if c["name"] not in group["users"]:
                group["users"].append(c["name"])

    out = [
        "## Components bundled in the firmware and web client",
        "",
        render_table(["Component", "License", "URL", "Copyright"], rows),
        "",
        "## License texts",
        "",
        "Copyright notices are in the table above.",
    ]
    for group in sorted(groups.values(), key=lambda g: g["ids"][0].lower()):
        out += ["", "### " + ", ".join(sorted(group["ids"])), "", "Used by: " + ", ".join(group["users"]), "",
                fence(group["body"])]

    notices = [c for c in components if c["notice"]]
    if notices:
        out += ["", "## Upstream notices"]
    for c in notices:
        out += ["", "### " + c["name"], "", fence(c["notice"])]
    out += ["", "<!-- notice-hash: %s -->" % compute_hash(), ""]
    return "\n".join(out)


def generate(args):
    text = read_text(_NOTICE_MD)
    if MARKER not in text:
        sys.exit("notice: marker line missing in NOTICE.md")
    head = text[:text.index(MARKER) + len(MARKER)]
    components = zephyr_components(args.spdx_dirs, args.west_list) + web_components()
    with open(_NOTICE_MD, "w", encoding="utf-8") as f:
        f.write(head + "\n\n" + render(components))
    for w in warnings:
        sys.stderr.write("notice: warning: %s\n" % w)
    print("notice: wrote %s" % _NOTICE_MD)


def check(_args):
    m = HASH_RE.search(read_text(_NOTICE_MD))
    if not m or m.group(1) != compute_hash():
        sys.exit("NOTICE.md is out of date, run `make notice`")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    gen = sub.add_parser("generate")
    gen.add_argument("--west-list", required=True)
    gen.add_argument("spdx_dirs", nargs="+")
    gen.set_defaults(func=generate)
    sub.add_parser("check").set_defaults(func=check)
    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
